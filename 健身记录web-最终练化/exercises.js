/* ================= 自检代码（保留，请勿删除） ================= */
(function () {
  var list = window.EXERCISES || [];
  var ENUM = {
    part:  ["胸", "背", "腿", "肩", "臂", "核心", "全身", "奥举", "有氧"],
    phase: ["warmup", "main"],
    type:  ["weight", "bodyweight"],
    mode:  ["reps", "time"],
    equip: ["杠铃", "哑铃", "壶铃", "绳索", "器械", "弹力带", "徒手", "其他"]
  };
  var FIELDS = ["id", "name", "part", "phase", "type", "mode", "equip"];
  var problems = [];
  var seenId = {};
  var seenName = {};

  for (var i = 0; i < list.length; i++) {
    var ex = list[i];
    var tag = "第" + (i + 1) + "条(" + (ex && ex.id ? ex.id : "?") + ")";

    for (var f = 0; f < FIELDS.length; f++) {
      var key = FIELDS[f];
      var val = ex ? ex[key] : undefined;
      if (val === undefined || val === null || val === "") {
        problems.push(tag + " 缺少字段 " + key);
      }
    }
    if (!ex) continue;

    if (!/^EX\d{4}$/.test(ex.id)) {
      problems.push(tag + " id 格式非法：" + ex.id);
    } else if (seenId[ex.id]) {
      problems.push(tag + " id 重复：" + ex.id + "（与" + seenId[ex.id] + "重复）");
    } else {
      seenId[ex.id] = tag;
    }

    if (seenName[ex.name]) {
      problems.push(tag + " name 重复：" + ex.name);
    } else {
      seenName[ex.name] = tag;
    }

    for (var k in ENUM) {
      if (ex[k] !== undefined && ENUM[k].indexOf(ex[k]) === -1) {
        problems.push(tag + " " + k + " 取值非法：" + ex[k]);
      }
    }
  }

  if (problems.length > 0) {
    for (var p = 0; p < problems.length; p++) {
      console.error(problems[p]);
    }
    console.error("动作库自检未通过，共 " + problems.length + " 处问题，条目总数 " + list.length);
  } else {
    console.log("动作库自检通过，共 " + list.length + " 条");
  }
})();
